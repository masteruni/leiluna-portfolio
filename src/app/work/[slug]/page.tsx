// Break a title into two lines: at a comma if it has one, otherwise in the middle.
function titleLines(title: string) {
  const comma = title.indexOf(", ");
  if (comma > 0) return [title.slice(0, comma + 1), title.slice(comma + 2)];
  const words = title.split(" ");
  const half = Math.ceil(words.length / 2);
  return [words.slice(0, half).join(" "), words.slice(half).join(" ")].filter(Boolean);
}

export function generateStaticParams() {
  return projects.map((p) => ({ slug: p.slug }));
}

export async function generateMetadata({ params }: PageProps<"/work/[slug]">): Promise<Metadata> {
  const { slug } = await params;
  const project = getProject(slug);
  if (!project) return {};
  const title = `${project.title}, ${project.client}`;
  return {
    title,
    description: project.summary,
    alternates: { canonical: `/work/${project.slug}` },
    openGraph: {
      title,
      description: project.summary,
      type: "article",
      url: `/work/${project.slug}`,
      // The preview image is generated by ./opengraph-image.tsx.
    },
    twitter: { card: "summary_large_image", title, description: project.summary },
  };
}

export default async function CaseStudy({ params }: PageProps<"/work/[slug]">) {
  const { slug } = await params;
  const project = getProject(slug);
  if (!project) notFound();

  const index = projects.indexOf(project);
  const next = projects[(index + 1) % projects.length];
  const prev = projects[(index - 1 + projects.length) % projects.length];

  // Search engines get the case study as a piece of work by the studio, plus a breadcrumb trail.
  const schema = [
    {
      "@context": "https://schema.org",
      "@type": "CreativeWork",
      name: `${project.title}, ${project.client}`,
      description: project.summary,
      url: `${site.url}/work/${project.slug}`,
      creator: { "@type": "Organization", name: site.name, url: site.url },
      about: project.client,
      keywords: [...project.categories, ...project.deliverables].join(", "),
      ...(project.cover ? { image: `${site.url}${project.cover}` } : {}),
    },
    {
      "@context": "https://schema.org",
      "@type": "BreadcrumbList",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: "Work", item: `${site.url}/#work` },
        { "@type": "ListItem", position: 2, name: project.client, item: `${site.url}/work/${project.slug}` },
      ],
    },
  ];
  // Landscape formats get a full-width hero; vertical ones sit beside the text.
  const isTall = project.format === "reel" || project.format === "portrait";

  return (
    <>
      <Nav />
      <main id="main" className="pt-32 md:pt-40">
        <article className="mx-auto max-w-7xl px-5 sm:px-10 xl:box-content">
          <Reveal css>
            <div className="flex flex-wrap items-center justify-between gap-4">
              <Link href="/#work" className="inline-flex items-center gap-2 text-sm text-muted transition-colors hover:text-paper pointer-coarse:min-h-11">
                <ArrowLeft size={16} /> All work
              </Link>
              <ShareButton title={`${project.title}, ${project.client}`} text={project.summary} />
            </div>
          </Reveal>

          <div className={`mt-10 grid gap-12 ${isTall ? "lg:grid-cols-[1.2fr_0.8fr] lg:items-end" : ""}`}>
            <div>
              {/* The title rises line by line on its own; the lines around it only fade in, so the words never move twice.
                  All of this runs in CSS, so it shows the moment the page arrives, not after the scripts load. */}
              <Reveal css y={0}>
                <p className="text-xs text-muted">
                  <span className="text-accent">{project.client}</span>, {project.year}
                </p>
              </Reveal>
              <h1 className="mt-5 font-display text-[clamp(3.2rem,9vw,8rem)] font-bold leading-[0.88] tracking-[-0.045em]">
                <LineReveal css delay={0.05} lines={titleLines(project.title)} />
              </h1>
              <Reveal css y={0} delay={0.15}>
                <p className="mt-6 max-w-2xl text-xl leading-relaxed text-muted">{project.summary}</p>
              </Reveal>

              <Reveal css delay={0.1}>
                <dl className="mt-12 grid grid-cols-3 gap-6 border-t border-line pt-6">
                  {project.metrics.map((m) => (
                    <div key={m.label} className="flex flex-col-reverse justify-end">
                      <dt className="mt-2 text-xs text-muted sm:text-sm">{m.label}</dt>
                      <dd className="font-display text-3xl font-semibold tracking-tight text-accent sm:text-5xl">
                        <CountUp value={m.value} />
                      </dd>
                    </div>
                  ))}
                </dl>
              </Reveal>
            </div>

            {/* The cover arrives by morphing out of the card on the homepage (same view-transition name there),
                so it isn't faded in like the text around it. */}
            <div className={isTall ? "mx-auto w-full max-w-sm" : ""}>
              <ViewTransition name={`cover-${project.slug}`} share="cover-morph" default="none">
                {/* not a link, so no hover zoom (ProjectCover zooms inside a `group`) */}
                <ProjectCover project={project} priority />
              </ViewTransition>
            </div>
          </div>

          <div className="mt-24 grid gap-16 lg:grid-cols-[1fr_280px]">
            <div className="space-y-16">
              <Reveal>
                <section>
                  <h2 className="text-xs text-accent">The challenge</h2>
                  {/* lights up word by word as it's read, like the studio statement on the homepage */}
                  <LitText text={project.challenge} className="serif mt-4 text-3xl leading-tight sm:text-5xl" />
                </section>
              </Reveal>
              <Reveal>
                <section>
                  <h2 className="text-xs text-accent">The approach</h2>
                  <ul className="mt-6 space-y-6">
                    {project.approach.map((a) => {
                      // "Video editing: cut quote reels…" reads as a name and what was done: set them side by side,
                      // so the five disciplines can be scanned down the left edge.
                      const cut = a.indexOf(": ");
                      const [name, done] = cut > 0 ? [a.slice(0, cut), a.slice(cut + 2)] : ["", a];
                      return (
                        <li key={a} className="grid gap-x-8 gap-y-1.5 border-t border-line pt-5 sm:grid-cols-[12rem_1fr]">
                          {name && <h3 className="font-display text-lg font-medium leading-relaxed">{name}</h3>}
                          <p className={`text-lg leading-relaxed ${name ? "text-paper/70" : "sm:col-span-2"}`}>
                            {name ? done.charAt(0).toUpperCase() + done.slice(1) : done}
                          </p>
                        </li>
                      );
                    })}
                  </ul>
                </section>
              </Reveal>
              <Reveal>
                <section>
                  <h2 className="text-xs text-accent">The results</h2>
                  <p className="serif mt-4 text-3xl leading-tight text-brand-2 light:text-accent sm:text-5xl">{project.results}</p>
                </section>
              </Reveal>
            </div>

            <Reveal>
              <div className="space-y-8 lg:sticky lg:top-28">
                <div>
                  <h2 className="text-xs text-muted">Deliverables</h2>
                  <ul className="mt-3 space-y-2">
                    {project.deliverables.map((d) => (
                      <li key={d} className="border-b border-line pb-2">{d}</li>
                    ))}
                  </ul>
                </div>
                <div>
                  <h2 className="text-xs text-muted">Platforms</h2>
                  <ul className="mt-3 flex flex-wrap gap-2">
                    {project.platforms.map((p) => (
                      <li key={p} className="rounded-full border border-line px-3 py-1.5 text-sm">{p}</li>
                    ))}
                  </ul>
                </div>
              </div>
            </Reveal>
          </div>

          {/* gallery: real media from `project.gallery`, or generated placeholders until a cover is added */}
          {project.gallery?.length ? (
            <div className="mt-24 columns-1 gap-4 sm:columns-2 lg:columns-3">
              {project.gallery.map((src, i) => (
                <Reveal key={src} className="mb-4 break-inside-avoid overflow-hidden rounded-2xl bg-ink-2">
                  {/\.(mp4|webm|mov)$/i.test(src) ? (
                    <video controlsList="nodownload noplaybackrate noremoteplayback" disablePictureInPicture disableRemotePlayback src={src} autoPlay muted loop playsInline preload="metadata" className="block h-auto w-full" />
                  ) : (
                    // These are the client's own screenshots, and the proof is in their small print (likes, reposts,
                    // view counts): with a mouse, a magnifying glass follows the pointer so it can be read. The
                    // glass shows a sharper copy, fetched the first time it's used.
                    <Lens
                      magnified={
                        <Image src={src} alt="" width={1200} height={1500} sizes="(min-width: 1024px) 66vw, 100vw" className="block h-auto w-full" />
                      }
                    >
                      <Image
                        src={src}
                        alt={`${project.title}, image ${i + 1}`}
                        width={1200}
                        height={1500}
                        sizes="(min-width: 1024px) 33vw, (min-width: 640px) 50vw, 100vw"
                        className="block h-auto w-full"
                      />
                    </Lens>
                  )}
                </Reveal>
              ))}
            </div>
          ) : (
            !project.cover && (
              <Reveal>
                <div className="mt-24 grid grid-cols-2 gap-4 md:grid-cols-3">
                  <ProjectCover project={project} format="reel" variant={1} />
                  <div className="flex flex-col gap-4">
                    <ProjectCover project={project} format="square" variant={2} />
                    <ProjectCover project={project} format="portrait" variant={3} />
                  </div>
                  <div className="hidden md:block"><ProjectCover project={project} format="reel" variant={4} /></div>
                </div>
              </Reveal>
            )
          )}

          <nav aria-label="More case studies" className="mt-32 border-y border-line">
            {/* with a mouse, the next project's cover trails the pointer over its title */}
            <HoverPreview preview={<ProjectCover project={next} />}>
            <Link
              href={`/work/${next.slug}`}
              className="group flex items-end justify-between gap-6 py-12"
            >
              <div>
                <p className="text-xs text-muted">Next project: {next.client}</p>
                <p className="mt-3 font-display text-5xl font-bold tracking-[-0.04em] transition-colors duration-300 group-hover:text-accent sm:text-8xl">
                  {next.title}
                </p>
              </div>
              <ArrowCircle size="lg" tone="outline" />
            </Link>
            </HoverPreview>
            {prev.slug !== next.slug && (
              <Link
                href={`/work/${prev.slug}`}
                className="group flex items-center justify-between gap-6 border-t border-line py-6 text-sm text-muted transition-colors hover:text-paper"
              >
                <span className="inline-flex items-center gap-2">
                  <ArrowLeft size={16} /> Previous: {prev.title}
                </span>
                <span className="text-xs">{prev.client}</span>
              </Link>
            )}
          </nav>
          <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(schema) }} />
        </article>
        <Dusk />
        <Contact />
      </main>
      <Footer />
    </>
  );
}
